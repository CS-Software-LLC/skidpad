#!/usr/bin/env node
// Writes packages/core/src/channels.ts, the telemetry channel names as a
// TypeScript union, from the built core's layout. Run after adding a
// channel in crates/skidpad-core/src/telemetry.rs (and `pnpm build:wasm`);
// a core test fails while the file is out of date.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { root } from "./lib/wasm-artifact.mjs";

const { init } = await import(join(root, "packages", "core", "dist", "index.js"));
const sp = await init();
const names = sp.telemetryLayout.map((c) => c.name);
const body = names.map((n) => `  "${n}",`).join("\n");
writeFileSync(
  join(root, "packages", "core", "src", "channels.ts"),
  `// Generated by scripts/gen-channels.mjs from the core's telemetry layout. Do not edit.

/** Every telemetry channel name, in layout order. */
export const CHANNEL_NAMES = [
${body}
] as const;

/** A telemetry channel name; \`World.read\` checks it at compile time. */
export type ChannelName = (typeof CHANNEL_NAMES)[number];
`,
);
console.log(`[gen-channels] ${names.length} channels -> packages/core/src/channels.ts`);
