// Shared helpers for placing a compiled core where the packages expect it.
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const wasmOut = join(root, "packages", "core", "wasm", "skidpad.wasm");
export const inlineOut = join(root, "packages", "core", "src", "generated", "wasm-inline.ts");
export const prebuiltDir = join(root, "prebuilt");
export const prebuiltWasm = join(prebuiltDir, "skidpad.wasm");
export const prebuiltManifest = join(prebuiltDir, "manifest.json");

/** Write the .wasm next to the core package and the base64 inline module. */
export function installWasm(bytes) {
  mkdirSync(dirname(wasmOut), { recursive: true });
  writeFileSync(wasmOut, bytes);
  mkdirSync(dirname(inlineOut), { recursive: true });
  writeFileSync(
    inlineOut,
    `// Generated by scripts/. Do not edit.\n// Inline copy of skidpad.wasm for the compat build (works in any bundler).\nexport const wasmBase64 = "${Buffer.from(bytes).toString("base64")}";\n`,
  );
}

function walk(dir, out) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== "target") walk(p, out);
    } else {
      out.push(p);
    }
  }
}

/**
 * Hash of everything that determines the compiled core: the crates, the
 * workspace manifest and lockfile, and the toolchain pin. Line endings are
 * normalised so checkouts with autocrlf agree.
 */
export function sourceHash() {
  const files = [];
  walk(join(root, "crates"), files);
  for (const f of ["Cargo.toml", "Cargo.lock", "rust-toolchain.toml", "clippy.toml"])
    files.push(join(root, f));
  files.sort();
  const h = createHash("sha256");
  for (const f of files) {
    if (!statSync(f).isFile()) continue;
    h.update(relative(root, f).split("\\").join("/"));
    h.update("\0");
    h.update(readFileSync(f).toString("utf8").replace(/\r\n/g, "\n"));
    h.update("\0");
  }
  return h.digest("hex");
}
